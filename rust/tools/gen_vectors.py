"""Generates KDF test vectors for the nat20 Rust crate.

Independent implementation using only the Python standard library
(hmac/hashlib), mirroring the libnat20 derivations:
  - next CDI      = HKDF-Expand-SHA512(cdi, SHA512(inputs) || "CDI_Attest", 32)
  - key seed      = HKDF-Expand-SHA512(cdi, ASYM_SALT || "Key Pair Attest", 32)
  - CDI_ID        = HKDF-SHA512(ikm=pubkey, salt=ID_SALT, info="ID", 20),
                    first byte masked with 0x7f

Output is Rust source to paste into nat20/tests/vectors.rs.
"""

import hashlib
import hmac


def hkdf_expand_sha512(prk: bytes, info: bytes, length: int) -> bytes:
    okm = b""
    t = b""
    i = 1
    while len(okm) < length:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha512).digest()
        okm += t
        i += 1
    return okm[:length]


def hkdf_sha512(ikm: bytes, salt: bytes, info: bytes, length: int) -> bytes:
    prk = hmac.new(salt, ikm, hashlib.sha512).digest()
    return hkdf_expand_sha512(prk, info, length)


ASYM_SALT = bytes.fromhex(
    "63b6a04d2c077fc10f639f21da793844"
    "356cc2b0b441b3a77124035c03f8e1be"
    "6035d31f282821a7450a02222ab1b3cf"
    "f1679b05ab1ca5d1affb789ccd2b0b3b"
)
ID_SALT = bytes.fromhex(
    "dbdbaebc8020da9ff0dd5a24c83aa5a5"
    "4286dfc263031e329b4da148430659fe"
    "62cdb5b7e1e00fc680306711eb444af7"
    "7209359496fcff1db9520ba51c7b29ea"
)

CDI = bytes(range(32))  # 000102...1f
PUBKEY = bytes(range(0x20, 0x40))  # 202122...3f

# compress_input for: code_hash = [0xC0]*64, config_descriptor = [0xC1]*64
# (no config hash), authority_hash = [0xC2]*64, mode = 1 (normal),
# hidden = [0xC3]*32.
code_hash = b"\xc0" * 64
config_desc = b"\xc1" * 64
authority_hash = b"\xc2" * 64
mode = b"\x01"
hidden = b"\xc3" * 32
input_digest = hashlib.sha512(
    code_hash + config_desc + authority_hash + mode + hidden
).digest()

next_cdi = hkdf_expand_sha512(CDI, input_digest + b"CDI_Attest", 32)
key_seed = hkdf_expand_sha512(CDI, ASYM_SALT + b"Key Pair Attest", 32)
cdi_id = bytearray(hkdf_sha512(PUBKEY, ID_SALT, b"ID", 20))
cdi_id[0] &= 0x7F

# A long-output expand crossing the 64-byte block boundary, to exercise the
# multi-block loop.
long_okm = hkdf_expand_sha512(CDI, b"multi-block-test", 100)


def rust_array(name: str, data: bytes) -> str:
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"pub const {name}: [u8; {len(data)}] = [{body}];"


print("// Generated by tools/gen_vectors.py — do not edit.")
print(rust_array("VEC_CDI", CDI))
print(rust_array("VEC_PUBKEY", PUBKEY))
print(rust_array("VEC_INPUT_DIGEST", input_digest))
print(rust_array("VEC_NEXT_CDI", next_cdi))
print(rust_array("VEC_KEY_SEED", key_seed))
print(rust_array("VEC_CDI_ID", bytes(cdi_id)))
print(rust_array("VEC_LONG_OKM", long_okm))
