fn test_input() -> OpenDiceInput<'static> {
    OpenDiceInput {
        code_hash: &[0xc0; 64],
        configuration_descriptor: &[0xc1; 64],
        authority_hash: &[0xc2; 64],
        mode: Mode::Normal,
        hidden: &[0xc3; 32],
        ..Default::default()
    }
}

#[test]
fn compress_input_matches_vector() {
    let mut c = SoftCrypto;
    let digest = compress_input(&mut c, &test_input()).unwrap();
    assert_eq!(digest, VEC_INPUT_DIGEST);
}

#[test]
fn compress_input_prefers_configuration_hash() {
    // With a configuration hash present, the descriptor must be ignored.
    let mut c = SoftCrypto;
    let mut with_hash = test_input();
    with_hash.configuration_hash = &[0xc1; 64];
    with_hash.configuration_descriptor = &[0xde; 64];
    let mut without_desc = test_input();
    without_desc.configuration_hash = &[0xc1; 64];
    without_desc.configuration_descriptor = &[];
    assert_eq!(
        compress_input(&mut c, &with_hash).unwrap(),
        compress_input(&mut c, &without_desc).unwrap()
    );
}

#[test]
fn next_cdi_matches_vector() {
    let mut c = SoftCrypto;
    let cdi = CdiSecret::from_bytes(VEC_CDI);
    let mut next = CdiSecret::default();
    next_cdi_attest(&mut c, &cdi, &VEC_INPUT_DIGEST, &mut next).unwrap();
    assert_eq!(*next.as_bytes(), VEC_NEXT_CDI);
}

#[test]
fn attest_key_seed_matches_vector() {
    let mut c = SoftCrypto;
    let cdi = CdiSecret::from_bytes(VEC_CDI);
    let mut seed = Seed32::default();
    attest_key_seed(&mut c, &cdi, &mut seed).unwrap();
    assert_eq!(*seed.as_bytes(), VEC_KEY_SEED);
}

#[test]
fn cdi_id_matches_vector_and_masks_high_bit() {
    let mut c = SoftCrypto;
    let id = cdi_id(&mut c, &VEC_PUBKEY).unwrap();
    assert_eq!(id, VEC_CDI_ID);
    assert!(id[0] & 0x80 == 0);
}

#[test]
fn hkdf_expand_multi_block() {
    let mut c = SoftCrypto;
    let mut okm = [0u8; 100];
    hkdf_expand_sha512(&mut c, &VEC_CDI, &[b"multi-block-test"], &mut okm).unwrap();
    assert_eq!(okm, VEC_LONG_OKM);
}

#[test]
fn hkdf_rfc5869_shape() {
    // Cross-check full HKDF against expand-of-extract computed separately.
    let mut c = SoftCrypto;
    let mut direct = [0u8; 20];
    hkdf_sha512(
        &mut c,
        &VEC_PUBKEY,
        &nat20::derive::ID_SALT,
        &[b"ID"],
        &mut direct,
    )
    .unwrap();
    let mut masked = direct;
    masked[0] &= 0x7f;
    assert_eq!(masked, VEC_CDI_ID);
}

#[test]
fn info_gather_list_is_concatenation() {
    // Splitting the info across gather parts must not change the result.
    let mut c = SoftCrypto;
    let mut a = [0u8; 32];
    let mut b = [0u8; 32];
    hkdf_expand_sha512(&mut c, &VEC_CDI, &[b"multi-", b"block-test"], &mut a).unwrap();
    hkdf_expand_sha512(&mut c, &VEC_CDI, &[b"multi-block-test"], &mut b).unwrap();
    assert_eq!(a, b);
}

#[test]
fn info_gather_list_has_no_part_limit() {
    // One part per byte, more than the four the fixed-size list once
    // allowed, and spanning several output blocks.
    let info = b"multi-block-test";
    let parts: Vec<&[u8]> = info.chunks(1).collect();
    let mut c = SoftCrypto;
    let mut a = [0u8; 200];
    let mut b = [0u8; 200];
    hkdf_expand_sha512(&mut c, &VEC_CDI, &parts, &mut a).unwrap();
    hkdf_expand_sha512(&mut c, &VEC_CDI, &[info], &mut b).unwrap();
    assert_eq!(a, b);
}
